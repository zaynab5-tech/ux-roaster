import { SEVERITY_META, type UxAuditReport } from '../types/audit';
import { computeWcagContrast, evaluateWcagStatus } from './contrast';

export function buildMarkdownReport(report: UxAuditReport, assetName: string): string {
  const lines: string[] = [];
  const timestamp = new Date().toISOString().split('T')[0];

  lines.push(`# UX Roaster Design Audit — ${assetName}`);
  lines.push(
    `**Date:** ${timestamp} | **Overall Grade:** ${report.overallGrade} (${report.overallScore}/100) | **WCAG 2.1 Verdict:** ${report.wcagVerdict}`
  );
  lines.push('');
  lines.push(`## Executive Verdict`);
  lines.push(report.verdictSummary);
  lines.push('');

  if (report.flowSummary) {
    lines.push(`## App Flow & Cross-Screen Consistency`);
    lines.push(report.flowSummary);
    lines.push('');
    if (report.flowFindings && report.flowFindings.length > 0) {
      for (const f of report.flowFindings) {
        const sev = SEVERITY_META[f.severity];
        lines.push(`### ${f.title} (${f.stepsAffected}) [\`${sev.shortLabel}\`]`);
        lines.push(`- **What's happening:** ${f.whatsHappening}`);
        lines.push(`- **Why it matters:** ${f.whyItMatters}`);
        lines.push(`- **Quick Fix:** ${f.quickFix}`);
        lines.push('');
      }
    }
  }

  if (report.strengths.length > 0) {
    lines.push(`### What Works Well`);
    for (const s of report.strengths) {
      lines.push(`- ${s}`);
    }
    lines.push('');
  }

  lines.push(`## Annotated Issues (${report.issues.length})`);
  lines.push('');
  for (const issue of report.issues) {
    const sev = SEVERITY_META[issue.severity];
    const screenTag = issue.screenLabel ? ` · ${issue.screenLabel}` : '';
    lines.push(
      `### #${String(issue.id).padStart(2, '0')} — ${issue.title}${screenTag} [\`${sev.shortLabel}\`]`
    );
    lines.push(
      `- **Element:** ${issue.elementLabel} (Box: x=${issue.box.x.toFixed(1)}%, y=${issue.box.y.toFixed(1)}%, w=${issue.box.width.toFixed(1)}%, h=${issue.box.height.toFixed(1)}%)`
    );
    lines.push(`- **Rule:** ${issue.heuristicId} — ${issue.heuristicName}`);
    if (issue.wcagCriterion && issue.wcagCriterion.toLowerCase() !== 'none') {
      lines.push(`- **WCAG 2.1:** ${issue.wcagCriterion}`);
    }
    lines.push(`- **What's happening:** ${issue.whatsHappening}`);
    lines.push(`- **Why it matters:** ${issue.whyItMatters}`);
    lines.push(`- **Quick Fix:** ${issue.quickFix}`);
    lines.push('');
  }

  lines.push(`## Jakob Nielsen's 10 Usability Heuristics Scorecard`);
  lines.push('');
  lines.push(`| ID | Heuristic | Severity | Observation | Quick Fix |`);
  lines.push(`| --- | --- | --- | --- | --- |`);
  for (const h of report.heuristics) {
    const sev = SEVERITY_META[h.severity];
    const finding = h.finding.replace(/\|/g, '\\|');
    const rec = h.recommendation.replace(/\|/g, '\\|');
    lines.push(`| ${h.id} | ${h.name} | \`${sev.shortLabel}\` | ${finding} | ${rec} |`);
  }
  lines.push('');

  lines.push(`## WCAG 2.1 Color-Contrast Flags`);
  lines.push('');
  if (report.contrastFlags.length === 0) {
    lines.push(`No contrast violations flagged.`);
  } else {
    lines.push(`| Element | Foreground | Background | Ratio | Status | Suggested FG |`);
    lines.push(`| --- | --- | --- | --- | --- | --- |`);
    for (const flag of report.contrastFlags) {
      const calc = computeWcagContrast(flag.foregroundHex, flag.backgroundHex);
      const status = evaluateWcagStatus(calc.ratio, flag.textSize, flag.wcagStatus);
      const ratioStr = calc.ratio ? calc.formattedRatio : flag.contrastRatio;
      lines.push(
        `| ${flag.element.replace(/\|/g, '\\|')} | \`${calc.fgValid}\` | \`${calc.bgValid}\` | ${ratioStr} | **${status}** | \`${flag.suggestedForegroundHex}\` |`
      );
    }
  }
  lines.push('');

  lines.push(`## Microcopy Makeover`);
  lines.push('');
  if (report.microcopyMakeovers.length === 0) {
    lines.push(`No microcopy rewrites flagged.`);
  } else {
    lines.push(`| Location | Current UI Text | Why It Fails | Clear, Action-Oriented Rewrite |`);
    lines.push(`| --- | --- | --- | --- |`);
    for (const m of report.microcopyMakeovers) {
      lines.push(
        `| ${m.location.replace(/\|/g, '\\|')} | "${m.originalText.replace(/\|/g, '\\|')}" | ${m.whyItFails.replace(/\|/g, '\\|')} | **"${m.rewrittenText.replace(/\|/g, '\\|')}"** |`
      );
    }
  }
  lines.push('');
  lines.push(`---`);
  lines.push(`*Generated by UX Roaster*`);

  return lines.join('\n');
}
